def main() -> None:
    out = ROOT / "gt.b"
    out.mkdir(exist_ok=True)
    for sid, doc in PASS2.items():
        (out / f"{sid}.json").write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"pass-2 GT written: {len(PASS2)} samples -> {out}")


if __name__ == "__main__":
    main()
