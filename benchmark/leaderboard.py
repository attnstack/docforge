# 职责：从 results/*.json 生成静态榜单页（GitHub Pages 友好：单文件、无 JS 依赖）。
# 排序键 = 各指标均值的均值；覆盖率一并展示，防止"只跑了 1 个样本"的虚高综合分。

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from benchmark.runner import METRIC_KEYS

_PAGE_TMPL = """<!doctype html>
<html lang="zh">
<head>
<meta charset="utf-8">
<title>docforge 中文解析 Benchmark 榜单</title>
<style>
body {{ font-family: -apple-system, "Segoe UI", "Microsoft YaHei", sans-serif; margin: 2rem auto; max-width: 60rem; padding: 0 1rem; color: #222; }}
table {{ border-collapse: collapse; width: 100%; margin: 1rem 0; }}
th, td {{ border: 1px solid #ddd; padding: 0.5rem 0.75rem; text-align: left; }}
th {{ background: #f5f5f5; }}
.warn {{ background: #fff8e1; border-left: 4px solid #f0a500; padding: 0.75rem 1rem; }}
footer {{ color: #777; font-size: 0.85rem; margin-top: 2rem; }}
</style>
</head>
<body>
<h1>docforge 中文解析 Benchmark</h1>
<p>数据集：<strong>{dataset}</strong> · 更新于 {date}</p>
<div class="warn">⚠️ {synthetic_note}</div>
<table>
<tr><th>排名</th><th>引擎</th><th>文本 1−CER ↑</th><th>阅读顺序 ↑</th><th>表格 TEDS ↑</th><th>标题树 ↑</th><th>综合 ↑</th></tr>
{rows}
</table>
<p>提交格式与指标口径见仓库 docs/benchmark.md。指标全部为确定性计算（无 LLM judge），同输入必得同分。</p>
<footer>generated by docforge leaderboard</footer>
</body>
</html>
"""


def build_leaderboard(results_dir: Path, out_html: Path) -> Path:
    rows_md: list[dict] = []
    for path in sorted(results_dir.glob("*.json")):
        if path.name == "report.md":
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        if "aggregate" in data:
            rows_md.append(data)
    if not rows_md:
        raise ValueError(f"{results_dir} 下没有可用的结果 JSON（先运行 docforge bench）")

    rows_md.sort(key=lambda r: -(r["aggregate"]["overall"] or 0))
    dataset = rows_md[0].get("dataset", "-")
    synthetic = any(r.get("synthetic") for r in rows_md)
    date = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    note = (
        "合成种子集：数字用于验证评测链路，不构成对真实文档的性能主张。"
        if synthetic
        else "指标口径与提交格式见 docs/benchmark.md。"
    )
    trs = []
    for rank, r in enumerate(rows_md, 1):
        agg = r["aggregate"]
        cells = [str(rank), _esc(r["engine"])]
        for k in METRIC_KEYS:
            m = agg[k]["mean"]
            cells.append("—" if m is None else f"{m:.4f} <small>({agg[k]['coverage']})</small>")
        cells.append("—" if agg["overall"] is None else f"<strong>{agg['overall']:.4f}</strong>")
        trs.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")

    out_html.parent.mkdir(parents=True, exist_ok=True)
    out_html.write_text(
        _PAGE_TMPL.format(dataset=_esc(dataset), date=date, synthetic_note=note, rows="\n".join(trs)),
        encoding="utf-8",
    )
    return out_html


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
